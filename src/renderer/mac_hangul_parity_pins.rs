/// 맥 PDF 가로선이 우리 조판과 전부 짝지어지던 쪽(80168)은 그대로 짝지어져야 한다 — 쪽 번호·표 괘선·행 높이·쪽 나눔 규칙의 회귀망.
/// 개선으로 선이 달라져 이 표가 깨지면 값을 지우지 말고 맥 PDF 로 다시 재서 갱신한다.
#[test]
fn pages_that_matched_mac_hangul_stay_matched() {
    let mut broken = Vec::new();
    for (page, expected) in FULL_MATCH_PAGES {
        let ys = page_horizontal_lines_pt(page - 1);
        let missing: Vec<f64> = expected
            .iter()
            .copied()
            .filter(|e| !ys.iter().any(|y| (y - e).abs() <= TOLERANCE_PT))
            .collect();
        if !missing.is_empty() {
            broken.push(format!("쪽 {page}: {missing:?}"));
        }
    }
    assert!(
        broken.is_empty(),
        "맥 한글과 짝지어지던 가로선이 어긋났다: {broken:#?}"
    );
}
