//! 맥 한글 12.30 정합 핀 — 맥 한글이 같은 바이트를 연 PDF 에서 잰 가로선 y 를 규칙 단위로 고정한다.
//!
//! 기대값은 디컴파일 코드가 아니라 **맥 한글 PDF 실측**(`80168_regulatory_analysis.hwp` 의 쪽별 가로선, pt)이고,
//! 규칙은 한컴 함수의 반환 결과 명세에서 왔다(표 위 = 앵커 줄 위 + 세로 오프셋 · 칸 높이 = max(선언, 바닥)).
//! 공식 PDF(`pdf/`)가 아니라 맥 PDF 라 이 저장소에는 PDF 를 두지 않고 값만 둔다.
//!
//! - G1: 공백만 든 호스트 하나가 앵커한 양수 오프셋 자리차지 표는 호스트 줄(15pt × 160% = 24pt)을 표 앞에 더하지 않는다.
//! - 걸침(rowspan) 블록 행 높이: 쪽 경계에서 갈릴 때 이 조각에서 칸이 온전히 끝나는 행은 선언 높이로 그린다.

use std::fs;
use std::path::Path;

const PX_PER_PT: f64 = 4.0 / 3.0;
/// 맥 PDF 와 우리 PDF 의 가로선은 ±0.5pt 안에서 짝을 짓는 것을 일치로 본다(코퍼스 A/B 와 같은 잣대).
const TOLERANCE_PT: f64 = 0.5;

fn page_horizontal_lines_pt(page_index: u32) -> Vec<f64> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("samples/80168_regulatory_analysis.hwp");
    let bytes = fs::read(&path).expect("samples/80168_regulatory_analysis.hwp");
    let doc = crate::wasm_api::HwpDocument::from_bytes(&bytes).expect("80168 파싱");
    let svg = doc.render_page_svg_native(page_index).expect("쪽 SVG");
    let xml = roxmltree::Document::parse(&svg).expect("SVG XML");
    let mut ys = Vec::new();
    for node in xml.descendants() {
        let num = |name: &str| node.attribute(name).and_then(|v| v.parse::<f64>().ok());
        if node.has_tag_name("line") {
            if let (Some(x1), Some(y1), Some(x2), Some(y2)) =
                (num("x1"), num("y1"), num("x2"), num("y2"))
            {
                if (y1 - y2).abs() < 0.01 && (x2 - x1).abs() > 50.0 * PX_PER_PT {
                    ys.push(y1 / PX_PER_PT);
                }
            }
        } else if node.has_tag_name("rect") {
            if let (Some(y), Some(w), Some(h)) = (num("y"), num("width"), num("height")) {
                if w > 50.0 * PX_PER_PT {
                    ys.push(y / PX_PER_PT);
                    if h > 2.0 {
                        ys.push((y + h) / PX_PER_PT);
                    }
                }
            }
        }
    }
    ys
}

fn assert_mac_lines(page: u32, expected_pt: &[f64], rule: &str) {
    let ys = page_horizontal_lines_pt(page - 1);
    let missing: Vec<f64> = expected_pt
        .iter()
        .copied()
        .filter(|e| !ys.iter().any(|y| (y - e).abs() <= TOLERANCE_PT))
        .collect();
    assert!(
        missing.is_empty(),
        "{rule}: 맥 한글 PDF 쪽 {page} 의 가로선 {missing:?}pt 가 우리 조판에 없다(±{TOLERANCE_PT}pt). 우리 선: {:?}",
        ys.iter().map(|y| (y * 10.0).round() / 10.0).collect::<Vec<_>>()
    );
}

